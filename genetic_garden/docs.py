"""The documentation site: long-form explanations of each algorithm.

Pages are assembled here and written out as plain static HTML, so they can
be served by the dev server, committed, or dropped straight into a site.
Every figure is generated by `diagrams`, which draws from the real code --
so the pictures cannot drift away from the implementation.
"""

from __future__ import annotations

import html
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence

from . import diagrams

# --------------------------------------------------------------------------
# page model
# --------------------------------------------------------------------------


@dataclass
class Section:
    heading: str
    body: str = ""
    figure: Optional[str] = None


@dataclass
class Page:
    slug: str
    title: str
    kicker: str
    standfirst: str
    source: str
    sections: List[Section] = field(default_factory=list)


def _p(*paragraphs: str) -> str:
    return "".join(f"<p>{t}</p>" for t in paragraphs)


def _ul(*items: str) -> str:
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def _code(text: str) -> str:
    return f"<pre><code>{html.escape(text)}</code></pre>"


def _callout(kicker: str, *paragraphs: str) -> str:
    return (f'<div class="callout"><span class="kicker">{kicker}</span>'
            + "".join(f"<p>{t}</p>" for t in paragraphs) + "</div>")


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    head = "".join(f"<th>{h}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
                   for r in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


