INDEX_BLURB = (
    "Seven algorithms, each one page. They are meant to be read in order, "
    "but every page stands on its own. Each figure is generated by the code "
    "it describes, so the pictures cannot drift away from the "
    "implementation.")


def _chrome(active: Optional[str]) -> str:
    links = []
    for page in PAGES:
        cls = ' class="on"' if page.slug == active else ""
        links.append(f'<a href="{page.slug}.html"{cls}>{page.title}</a>')
    return (
        '<div class="topbar">'
        '<a class="home" href="/">genetic-garden</a>'
        '<a href="index.html">how it works</a>'
        f'<nav>{"".join(links)}</nav></div>')


def _figure_html(name: str) -> str:
    fig = getattr(diagrams, "fig_" + name)()
    caption = html.escape(fig.caption) if fig.caption else ""
    return (f'<figure class="plate" id="fig-{name}">'
            f'<div class="frame">{fig.to_svg()}</div>'
            f'<figcaption>{caption}</figcaption></figure>')


def render_page(page: Page) -> str:
    """One documentation page, with every figure inlined."""
    idx = PAGES.index(page)
    prev_page = PAGES[idx - 1] if idx > 0 else None
    next_page = PAGES[idx + 1] if idx < len(PAGES) - 1 else None

    body = []
    for n, section in enumerate(page.sections, start=1):
        body.append('<section class="step">')
        body.append(f'<h2><span class="num">{n}</span>'
                    f'{html.escape(section.heading)}</h2>')
        if section.body:
            body.append(section.body)
        if section.figure:
            body.append(_figure_html(section.figure))
        body.append("</section>")

    nav = []
    if prev_page:
        nav.append(f'<a href="{prev_page.slug}.html">&larr; '
                   f'{html.escape(prev_page.title)}</a>')
    else:
        nav.append('<a href="index.html">&larr; all pages</a>')
    if next_page:
        nav.append(f'<a href="{next_page.slug}.html">'
                   f'{html.escape(next_page.title)} &rarr;</a>')
    else:
        nav.append('<a href="index.html">back to the index</a>')

    return (
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{html.escape(page.title)} &mdash; genetic-garden</title>"
        f'<meta name="description" content="{html.escape(page.standfirst)}">'
        '<link rel="stylesheet" href="docs.css">'
        "</head><body>"
        + _chrome(page.slug)
        + '<div class="layout">'
        + '<header class="page">'
        + f"<h1>{html.escape(page.title)}</h1>"
        + f'<p class="standfirst">{html.escape(page.standfirst)}</p>'
        + f'<p class="meta">source: <code>{html.escape(page.source)}</code>'
          f' &middot; every figure on this page is drawn by the code it '
          f'describes</p>'
        + "</header>"
        + "".join(body)
        + f'<footer class="page">{"".join(nav)}</footer>'
        + "</div></body></html>")


